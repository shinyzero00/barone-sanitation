import { writeFile } from 'node:fs/promises'
import openapiTS, { astToString } from 'openapi-typescript'

const response = await fetch(process.env.OPENAPI_URL ?? 'http://127.0.0.1:8080/openapi.json')
if (!response.ok) throw new Error(`OpenAPI fetch failed (${response.status})`)
const spec = await response.json()
for (const path of Object.values(spec.paths)) {
  for (const operation of Object.values(path)) {
    if (!operation?.parameters || !Array.isArray(operation.parameters)) continue
    operation.parameters = operation.parameters.filter(p => p.in !== 'cookie' &&
      !(p.in === 'header' && ['origin', 'x-csrf-token'].includes(p.name.toLowerCase())))
  }
}
const ast = await openapiTS(spec)
await writeFile(new URL('../src/api/schema.ts', import.meta.url), '// Generated by npm run api:generate. Do not edit.\n' + astToString(ast))
